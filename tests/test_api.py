"""Integration tests: exercise the real HTTP layer with FastAPI's TestClient."""
from pathlib import Path

import pytest
from fastapi.testclient import TestClient

from app.main import app, get_sot
from app.source_of_truth import YamlSourceOfTruth

client = TestClient(app)
GOOD, BROKEN = "sjc01-r01", "sjc01-r02-broken"


@pytest.fixture
def empty_sot(tmp_path: Path):
    """Dependency override: point the API at an empty source of truth."""
    app.dependency_overrides[get_sot] = lambda: YamlSourceOfTruth(tmp_path)
    yield
    app.dependency_overrides.clear()


def test_health_endpoints():
    assert client.get("/healthz").json() == {"status": "ok"}
    assert client.get("/readyz").status_code == 200


def test_list_racks():
    assert client.get("/api/v1/racks").json()["racks"] == [GOOD, BROKEN]


def test_list_racks_with_overridden_source(empty_sot):
    assert client.get("/api/v1/racks").json() == {"racks": []}


def test_unknown_rack_is_404():
    assert client.get("/api/v1/racks/nope").status_code == 404


def test_path_traversal_is_rejected():
    assert client.get("/api/v1/racks/..%2F..%2Fetc%2Fpasswd").status_code == 404


def test_validate_good_and_broken():
    assert client.post(f"/api/v1/racks/{GOOD}/validate").json()["valid"] is True
    body = client.post(f"/api/v1/racks/{BROKEN}/validate").json()
    assert body["valid"] is False and len(body["issues"]) >= 5


def test_render_good_rack():
    r = client.post(f"/api/v1/day0/racks/{GOOD}/render")
    assert r.status_code == 200
    assert set(r.json()["configs"]) == {"sjc01-r01-leaf1", "sjc01-r01-leaf2", "sjc01-spine1", "sjc01-spine2"}


def test_render_broken_rack_is_blocked():
    r = client.post(f"/api/v1/day0/racks/{BROKEN}/render")
    assert r.status_code == 422
    assert "issues" in r.json()["detail"]


def test_ztp_config_is_plain_text():
    r = client.get(f"/api/v1/day0/racks/{GOOD}/devices/sjc01-spine1/config")
    assert r.status_code == 200 and r.headers["content-type"].startswith("text/plain")
    assert r.text.startswith("! Generated by netauto")


def test_drift_round_trip():
    intended = client.get(f"/api/v1/day0/racks/{GOOD}/devices/sjc01-r01-leaf1/config").text
    ok = client.post("/api/v1/day2/drift", json={"rack_id": GOOD, "device": "sjc01-r01-leaf1",
                                                 "running_config": intended}).json()
    assert ok["in_sync"] is True
    bad = client.post("/api/v1/day2/drift", json={"rack_id": GOOD, "device": "sjc01-r01-leaf1",
                                                  "running_config": intended.replace("mtu 9214", "mtu 1500")}).json()
    assert bad["in_sync"] is False and "   mtu 9214" in bad["remediation"]


def test_anomaly_endpoint_and_input_validation():
    samples = [{"device": "d", "interface": "e", "metric": "m", "timestamp": t, "value": v}
               for t, v in enumerate([10, 11, 9, 10, 12, 10, 999])]
    body = client.post("/api/v1/monitoring/anomalies", json={"samples": samples}).json()
    assert body["anomaly_count"] == 1
    assert client.post("/api/v1/monitoring/anomalies", json={"samples": samples, "window": 1}).status_code == 422


def test_metrics_exposed():
    client.get("/healthz")
    assert 'netauto_requests_total{method="GET",path="/healthz",status="200"}' in client.get("/metrics").text
